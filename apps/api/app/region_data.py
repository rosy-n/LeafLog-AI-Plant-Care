"""시/군/구 단위 위치 참조 데이터.

위경도 원본은 공개 행정구역 좌표 데이터셋(hmmhmmhm/sigungu, MIT)에서 가져왔고
세종특별자치시만 별도로 보강했다. 기상청 격자좌표(nx/ny)는 위경도에서 매번
API를 호출할 필요 없이, 이 모듈을 처음 임포트할 때 LCC 투영 공식으로 한 번만
계산해 REGIONS에 박아둔다.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

# 기상청 동네예보 오픈API 활용가이드에 실린 LCC(Lambert Conformal Conic) 격자
# 변환 공식 그대로 — 임의로 만든 상수가 아니라 기상청이 배포하는 표준 계수다.
_RE = 6371.00877  # 지구 반경(km)
_GRID = 5.0  # 격자 간격(km)
_SLAT1 = 30.0  # 투영 위도1(degree)
_SLAT2 = 60.0  # 투영 위도2(degree)
_OLON = 126.0  # 기준점 경도(degree)
_OLAT = 38.0  # 기준점 위도(degree)
_XO = 43  # 기준점 X좌표(GRID)
_YO = 136  # 기준점 Y좌표(GRID)
_DEGRAD = math.pi / 180.0


def _latlon_to_kma_grid(lat: float, lon: float) -> tuple[int, int]:
    re = _RE / _GRID
    slat1 = _SLAT1 * _DEGRAD
    slat2 = _SLAT2 * _DEGRAD
    olon = _OLON * _DEGRAD
    olat = _OLAT * _DEGRAD

    sn = math.tan(math.pi * 0.25 + slat2 * 0.5) / math.tan(math.pi * 0.25 + slat1 * 0.5)
    sn = math.log(math.cos(slat1) / math.cos(slat2)) / math.log(sn)
    sf = math.tan(math.pi * 0.25 + slat1 * 0.5)
    sf = math.pow(sf, sn) * math.cos(slat1) / sn
    ro = math.tan(math.pi * 0.25 + olat * 0.5)
    ro = re * sf / math.pow(ro, sn)

    ra = math.tan(math.pi * 0.25 + lat * _DEGRAD * 0.5)
    ra = re * sf / math.pow(ra, sn)
    theta = lon * _DEGRAD - olon
    if theta > math.pi:
        theta -= 2.0 * math.pi
    elif theta < -math.pi:
        theta += 2.0 * math.pi
    theta *= sn

    x = math.floor(ra * math.sin(theta) + _XO + 0.5)
    y = math.floor(ro - ra * math.cos(theta) + _YO + 0.5)
    return int(x), int(y)


